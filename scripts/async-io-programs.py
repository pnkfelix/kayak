"""The I/O programs in the emitter's async mode (C381): each of
tests/kfx-io compiled by `kfx --async`, every procedure an `async fn`, its
`main` run as a task (`kayak_rt::suspend::run`, C378), into a crate of its
own under target/async-io; run as scripts/io-programs.py runs the
synchronous build, and compared with it: its standard output, its
standard error, its status, and the files it leaves. The synchronous
build is Fixpt's equal (io-programs.py, in the full check), so this one
is too.

usage: python3 -I scripts/async-io-programs.py
"""

import os
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROGRAMS = os.path.join(ROOT, "tests", "kfx-io")
OUT = os.path.join(ROOT, "target", "async-io")

WRAPPER = """// Generated by scripts/async-io-programs.py: runs tests/kfx-io/{name}, async.

#[path = "{path}"]
#[allow(warnings, clippy::all)]
#[rustfmt::skip]
mod program;

fn main() {{
    std::process::exit(kfx_io::status({main}));
}}
"""


def run(args, **kw):
    return subprocess.run(args, capture_output=True, **kw)


def read(path, default=b""):
    if not os.path.exists(path):
        return default
    with open(path, "rb") as f:
        return f.read()


def files_in(d):
    return sorted((n, read(os.path.join(d, n))) for n in os.listdir(d))


def outcome(args, stdin):
    with tempfile.TemporaryDirectory() as d:
        r = run(args, cwd=d, input=stdin, timeout=120)
        return (r.stdout, r.stderr, r.returncode, files_in(d))


def main():
    for p in ("kfx", "kfx-io"):
        r = run(["cargo", "build", "--release", "--quiet", "-p", p], cwd=ROOT, text=True)
        if r.returncode != 0:
            sys.stderr.write(r.stderr)
            sys.exit("async-io-programs: %s does not build" % p)
    kfx = os.path.join(ROOT, "target", "release", "kfx")
    names = sorted(n.rsplit(".", 1)[0] for n in os.listdir(PROGRAMS) if n.endswith(".kfx") or n.endswith(".unit"))
    shutil.rmtree(os.path.join(OUT, "src"), ignore_errors=True)
    src = os.path.join(OUT, "src")
    os.makedirs(os.path.join(src, "bin"))
    bins = []
    for name in names:
        m = name.replace("-", "_")
        unit = os.path.join(PROGRAMS, name + ".unit")
        if os.path.exists(unit):
            d = os.path.join(src, m)
            os.makedirs(d)
            r = run([kfx, "--async", unit, d])
            path = "../%s/mod.rs" % m
            text = b"".join(read(os.path.join(d, f)) for f in os.listdir(d))
        else:
            r = run([kfx, "--async", os.path.join(PROGRAMS, name + ".kfx")])
            with open(os.path.join(src, m + ".rs"), "wb") as f:
                f.write(r.stdout)
            path = "../%s.rs" % m
            text = r.stdout
        if r.returncode != 0:
            sys.stderr.write(r.stderr.decode())
            sys.exit("async-io-programs: kfx --async refuses " + name)
        fallible = b"pub async fn main() -> Result<" in text
        main = "|| kayak_rt::suspend::run(program::main())" + (
            ".unwrap_or_else(|u| kayak_rt::unreachable_unwind(u))" if fallible else "")
        with open(os.path.join(src, "bin", name + ".rs"), "w") as f:
            f.write(WRAPPER.format(name=name, path=path, main=main))
        bins.append(name)
    with open(os.path.join(OUT, "Cargo.toml"), "w") as f:
        f.write('''[package]
name = "async-io"
version = "0.0.0"
edition = "2024"
autobins = true

[dependencies]
kayak-rt = { path = "%s/crates/kayak-rt" }
kfx-io = { path = "%s/crates/kfx-io" }

[workspace]
''' % (ROOT, ROOT))
    with open(os.path.join(src, "lib.rs"), "w") as f:
        f.write("//! Generated by scripts/async-io-programs.py.\n")
    target = os.path.join(OUT, "target")
    r = run(["cargo", "build", "--release", "--quiet", "--manifest-path", os.path.join(OUT, "Cargo.toml")],
            text=True, env=dict(os.environ, CARGO_TARGET_DIR=target))
    if r.returncode != 0:
        sys.stdout.write(r.stderr[-6000:])
        sys.exit("async-io-programs: the async Rust does not build")
    differ = []
    for name in names:
        stdin = read(os.path.join(PROGRAMS, name + ".stdin"))
        args = read(os.path.join(PROGRAMS, name + ".args")).decode().split()
        mine = outcome([os.path.join(target, "release", name)] + args, stdin)
        theirs = outcome([os.path.join(ROOT, "target", "release", name)] + args, stdin)
        if mine != theirs:
            differ.append(name)
            for what, a, b in zip(("stdout", "stderr", "status", "files"), mine, theirs):
                if a != b:
                    print(f"async-io-programs: {name}: {what}: async {a!r}, synchronous {b!r}")
    if differ:
        sys.exit("async-io-programs: differ: " + ", ".join(differ))
    print(f"async-io-programs: each of {len(names)} programs, every procedure async, does as the synchronous build does")


main()
