"""Programs that do I/O (CLAUDES_CHOICES.md C49): tests/kfx-io/NAME.kfx,
each a KFX program whose `main` returns the exit status, run both ways and
compared: its standard output, its standard error, its status, and the
files it leaves in the directory it ran in.

usage: python3 -I scripts/io-programs.py [--bless]

A program of several files is NAME.unit, as the corpus's are (its Rust in
NAME/). Beside each program, optional: NAME.stdin, its standard input; NAME.args,
its arguments, separated by spaces. Kept beside it: NAME.rs, the Rust kfx
makes of it (golden, as the corpus's are; --bless rewrites it).

Fixpt runs `fixpt run kfx/prelude.fx NAME.kfx -- ARGS`; the Rust is a
binary of crates/kfx-io, src/bin/NAME.rs, which calls `main` and exits
with its low byte, or 70 if the run fails, as Fixpt does. Each runs in a
directory of its own, made empty. With no Fixpt clone, only the Rust is
built and run, and the script says so.
"""

import os
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROGRAMS = os.path.join(ROOT, "tests", "kfx-io")
CRATE = os.path.join(ROOT, "crates", "kfx-io")
BIN = os.path.join(CRATE, "src", "bin")

WRAPPER = """// Generated by scripts/io-programs.py: runs tests/kfx-io/{name}.

#[path = "../../../../tests/kfx-io/{path}"]
#[allow(warnings, clippy::all)]
#[rustfmt::skip]
mod program;

#[rustfmt::skip]
fn main() {{
    std::process::exit(kfx_io::status({main}));
}}
"""

# A `main` that may suspend (C45) is an `async fn`: run to its end.
ASYNC_MAIN = "|| kayak_rt::suspend::block(program::main()).unwrap_or_else(|u| kayak_rt::unreachable_unwind(u))"


def run(args, **kw):
    return subprocess.run(args, capture_output=True, **kw)


def fixpt():
    r = run([os.path.join(ROOT, "scripts", "fixpt.sh")], text=True)
    if r.returncode == 3:
        return None
    if r.returncode != 0:
        sys.stderr.write(r.stderr)
        sys.exit(r.returncode)
    return r.stdout.strip()


def read(path, default=b""):
    if not os.path.exists(path):
        return default
    with open(path, "rb") as f:
        return f.read()


def manifest(path):
    """A manifest's files, in order."""
    files = []
    with open(path) as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith(";"):
                files.append(os.path.join(os.path.dirname(path), line))
    return files


def files_in(d):
    return sorted((n, read(os.path.join(d, n))) for n in os.listdir(d))


def outcome(args, stdin):
    with tempfile.TemporaryDirectory() as d:
        r = run(args, cwd=d, input=stdin, timeout=120)
        return (r.stdout, r.stderr, r.returncode, files_in(d))


def main():
    bless = "--bless" in sys.argv[1:]
    r = run(["cargo", "build", "--release", "--quiet", "-p", "kfx"], cwd=ROOT, text=True)
    if r.returncode != 0:
        sys.stderr.write(r.stderr)
        sys.exit("io-programs: kfx does not build")
    kfx = os.path.join(ROOT, "target", "release", "kfx")
    names = sorted(n.rsplit(".", 1)[0] for n in os.listdir(PROGRAMS) if n.endswith(".kfx") or n.endswith(".unit"))
    stale = []
    for name in names:
        unit = os.path.join(PROGRAMS, name + ".unit")
        if os.path.exists(unit):
            with tempfile.TemporaryDirectory() as out:
                r = run([kfx, unit, out])
                made = {f: read(os.path.join(out, f)) for f in os.listdir(out)}
            where = os.path.join(PROGRAMS, name)
            kept = {f: read(os.path.join(where, f)) for f in os.listdir(where) if f.endswith(".rs")} if os.path.isdir(where) else {}
        else:
            r = run([kfx, os.path.join(PROGRAMS, name + ".kfx")])
            made = {name + ".rs": r.stdout}
            where = PROGRAMS
            kept = {name + ".rs": read(os.path.join(PROGRAMS, name + ".rs"), None)}
        if r.returncode != 0:
            sys.stderr.write(r.stderr.decode())
            sys.exit(f"io-programs: kfx refuses {name}")
        if made != kept:
            if bless:
                for f in kept:
                    if f not in made:
                        os.remove(os.path.join(where, f))
                for f, text in made.items():
                    with open(os.path.join(where, f), "wb") as g:
                        g.write(text)
            else:
                stale.append(name)
    if stale:
        sys.exit("io-programs: kfx makes other Rust of " + ", ".join(stale) + " (--bless, if it should)")
    shutil.rmtree(BIN, ignore_errors=True)
    os.makedirs(BIN)
    for name in names:
        unit = os.path.exists(os.path.join(PROGRAMS, name + ".unit"))
        path = name + "/mod.rs" if unit else name + ".rs"
        where = os.path.join(PROGRAMS, name) if unit else PROGRAMS
        rs = [os.path.join(where, f) for f in os.listdir(where) if f.endswith(".rs")] if unit else [os.path.join(PROGRAMS, path)]
        suspends = any(b"pub async fn main()" in read(f) for f in rs)
        with open(os.path.join(BIN, name + ".rs"), "w") as f:
            f.write(WRAPPER.format(name=name, path=path, main=ASYNC_MAIN if suspends else "program::main"))
    r = run(["cargo", "build", "--release", "--quiet", "-p", "kfx-io"], cwd=ROOT, text=True)
    if r.returncode != 0:
        sys.stderr.write(r.stderr)
        sys.exit("io-programs: the Rust does not build")
    binary = fixpt()
    if binary is None:
        print("io-programs: no Fixpt clone; the Rust built, not compared")
    differ = []
    for name in names:
        stdin = read(os.path.join(PROGRAMS, name + ".stdin"))
        args = read(os.path.join(PROGRAMS, name + ".args")).decode().split()
        rust = outcome([os.path.join(ROOT, "target", "release", name)] + args, stdin)
        if binary is None:
            continue
        unit = os.path.join(PROGRAMS, name + ".unit")
        files = manifest(unit) if os.path.exists(unit) else [os.path.join(PROGRAMS, name + ".kfx")]
        theirs = outcome(
            [binary, "--dialect", "fx26", "run", os.path.join(ROOT, "kfx", "prelude.fx")] + files + ["--"] + args,
            stdin,
        )
        if rust != theirs:
            differ.append(name)
            for what, a, b in zip(("stdout", "stderr", "status", "files"), rust, theirs):
                if a != b:
                    print(f"io-programs: {name}: {what}: Rust {a!r}, Fixpt {b!r}")
    if differ:
        sys.exit("io-programs: differ: " + ", ".join(differ))
    if binary is not None:
        print(f"io-programs: {len(names)} programs agree")


main()
