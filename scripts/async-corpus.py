"""The corpus in the emitter's async mode (C373): every program in tests/kfx
compiled by `kfx --async`, every procedure an `async fn`, into a crate of
its own under target/async-corpus, built, and each program's `main` run
to its end: its answer must be the one Fixpt gives, NAME.out, as the
synchronous build's must (scripts/corpus.py, crates/kfx-corpus). Nothing
is kept but the answers already kept: the async Rust is not golden.

usage: python3 -I scripts/async-corpus.py
"""

import os
import platform
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fixptcache  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CORPUS = os.path.join(ROOT, "tests", "kfx")
OUT = os.path.join(ROOT, "target", "async-corpus")


def run(args, **kw):
    return subprocess.run(args, capture_output=True, text=True, **kw)


def manifest(path):
    with open(path) as f:
        lines = [l.strip() for l in f]
    return [os.path.join(os.path.dirname(path), l) for l in lines if l and not l.startswith(";")]


def files_of_program(n):
    unit = os.path.join(CORPUS, n + ".unit")
    return manifest(unit) if os.path.exists(unit) else [os.path.join(CORPUS, n + ".kfx")]


def main():
    r = run(["cargo", "build", "--release", "--quiet", "-p", "kfx"], cwd=ROOT)
    if r.returncode != 0:
        sys.stderr.write(r.stderr)
        sys.exit("async-corpus: kfx does not build")
    kfx = os.path.join(ROOT, "target", "release", "kfx")
    names = sorted({f[:-4] for f in os.listdir(CORPUS) if f.endswith(".kfx")} |
                   {f[:-5] for f in os.listdir(CORPUS) if f.endswith(".unit")})
    names = [n for n in names if os.path.exists(os.path.join(CORPUS, n + ".out"))]
    src = os.path.join(OUT, "src")
    os.makedirs(src, exist_ok=True)
    refused, mods = [], []
    here = {"arm64": "aarch64"}.get(platform.machine(), platform.machine())
    for n in names:
        m = n.replace("-", "_")
        machine = fixptcache.machine_of(files_of_program(n))
        if machine is not None and machine != here:
            # A program of another machine's native convention, compiled and
            # run only there, as scripts/corpus.py has it (C135).
            continue
        unit = os.path.join(CORPUS, n + ".unit")
        if os.path.exists(unit):
            d = os.path.join(src, m)
            os.makedirs(d, exist_ok=True)
            r = run([kfx, "--async", unit, d])
            path = "%s/mod.rs" % m
        else:
            r = run([kfx, "--async", os.path.join(CORPUS, n + ".kfx")])
            if r.returncode == 0:
                with open(os.path.join(src, m + ".rs"), "w") as f:
                    f.write(r.stdout)
            path = m + ".rs"
        if r.returncode != 0:
            refused.append("%s: kfx --async refuses it:\n%s" % (n, r.stderr.strip()[-400:]))
            continue
        mods.append((n, m, path, machine))
    lib = ["//! Generated by scripts/async-corpus.py: the corpus in the async mode.", ""]
    for n, m, path, machine in mods:
        if machine is not None:
            lib.append('#[cfg(target_arch = "%s")]' % machine)
        lib += ["#[allow(warnings, clippy::all)]", '#[path = "%s"]' % path, "pub mod %s;" % m, ""]
    lib.append("pub type Main = fn() -> kayak_rt::Str;")
    for n, m, path, machine in mods:
        files = [path] if not path.endswith("/mod.rs") else [
            os.path.join(m, f) for f in os.listdir(os.path.join(src, m)) if f.endswith(".rs")]
        text = ""
        for p in files:
            with open(os.path.join(src, p)) as f:
                text += f.read()
        fallible = re.search(r"pub async fn main\(\) -> Result<", text) is not None
        if machine is not None:
            lib.append('#[cfg(target_arch = "%s")]' % machine)
        lib.append("fn %s_main() -> kayak_rt::Str {" % m)
        # A task of a scheduler of its own, which its fuel preempts (C378).
        lib.append("    kayak_rt::suspend::run(%s::main())%s" %
                   (m, ".unwrap_or_else(|u| kayak_rt::unreachable_unwind(u))" if fallible else ""))
        lib.append("}")
    lib.append("pub const PROGRAMS: &[(&str, Main)] = &[")
    for n, m, path, machine in mods:
        if machine is not None:
            lib.append('    #[cfg(target_arch = "%s")]' % machine)
        lib.append('    ("%s", %s_main),' % (n, m))
    lib.append("];")
    with open(os.path.join(src, "lib.rs"), "w") as f:
        f.write("\n".join(lib) + "\n")
    os.makedirs(os.path.join(OUT, "tests"), exist_ok=True)
    with open(os.path.join(OUT, "tests", "corpus.rs"), "w") as f:
        f.write('''#[test]
fn every_program_gives_fixpts_answer() {
    let dir = "%s";
    let platform = format!("{}-{}", std::env::consts::ARCH, std::env::consts::OS);
    let mut wrong = Vec::new();
    for &(name, main) in async_corpus::PROGRAMS {
        let mine = format!("{dir}/{name}.{platform}.out");
        let path = if std::path::Path::new(&mine).exists() { mine } else { format!("{dir}/{name}.out") };
        let want = std::fs::read_to_string(&path).unwrap();
        let got = kayak_rt::with_big_stack(main);
        if got.text() != want {
            wrong.push(format!("{name}:\\n  Fixpt: {want:?}\\n  async: {got:?}"));
        }
    }
    assert!(wrong.is_empty(), "{}", wrong.join("\\n"));
}
''' % CORPUS)
    with open(os.path.join(OUT, "Cargo.toml"), "w") as f:
        f.write('''[package]
name = "async-corpus"
version = "0.0.0"
edition = "2024"

[dependencies]
kayak-rt = { path = "%s/crates/kayak-rt" }

[workspace]
''' % ROOT)
    for x in refused:
        print("async-corpus: " + x)
    r = subprocess.run(["cargo", "test", "--release", "--quiet", "--manifest-path", os.path.join(OUT, "Cargo.toml")],
                       capture_output=True, text=True, env=dict(os.environ, CARGO_TARGET_DIR=os.path.join(OUT, "target")))
    if r.returncode != 0:
        sys.stdout.write(r.stdout[-6000:])
        sys.stdout.write(r.stderr[-6000:])
        print("async-corpus: %d of %d programs compiled; the crate fails" % (len(mods), len(names)))
        return 1
    if refused:
        print("async-corpus: %d programs kfx --async refuses" % len(refused))
        return 1
    print("async-corpus: each of %d programs (of %d; others another machine's), every procedure async, gives Fixpt's answer" % (len(mods), len(names)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
