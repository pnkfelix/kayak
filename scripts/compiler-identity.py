"""The compiler's identity (C387): kfx/identity.kfx, a fingerprint of the
compiler's sources, which the driver writes in its memo file's first line
and asks of a memo file it is given, so that one compiler's memos are never
another's (C54's memos say what a form's Rust was made from, not by which
compiler). Of the files of kfx/kfx.unit, identity.kfx itself left out, and
kfx/prelude.fx; not kayak-rt's Rust, which runs the compiler and says
nothing of what it writes. KFX, so that Fixpt running the compiler has the
same identity, and the fixpoint check's memos are taken by either.

And kc's alike (C399): kc/identity.kfx, of kc/kc.unit's files, its own
left out, the expander it loads (C446), and its runtime (C448: a
transformer's answer, kept in the database, is the runtime's run of it),
which kc writes in its database's first line (`--db`), so that a
database another kc made is never taken for this one's.

usage: python3 -I scripts/compiler-identity.py [--check]
  writes kfx/identity.kfx and kc/identity.kfx; with --check, says whether
  they are current.
"""

import hashlib
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KFX = os.path.join(ROOT, "kfx")
OUT = os.path.join(KFX, "identity.kfx")


def sources(unit_dir, unit, extra):
    d = os.path.join(ROOT, unit_dir)
    with open(os.path.join(d, unit)) as f:
        names = [l.strip() for l in f if l.strip() and not l.strip().startswith(";") and not l.strip().startswith("--")]
    files = [os.path.normpath(os.path.join(d, n)) for n in names if n != "identity.kfx"]
    return files + [os.path.join(d, e) for e in extra]


def identity(files):
    h = hashlib.sha256()
    for p in files:
        h.update(os.path.relpath(p, ROOT).encode() + b"\0")
        with open(p, "rb") as f:
            h.update(f.read())
        h.update(b"\0")
    return h.hexdigest()[:16]


def kfx_text(ident):
    return ('"identity.kfx: generated by scripts/compiler-identity.py (C387), a\n'
            ' fingerprint of the compiler\'s sources: the driver keeps a memo file\n'
            ' as this compiler\'s, and takes none of another\'s. Not to be edited."\n'
            '(define compiler-identity string "%s")\n' % ident)


def kc_text(ident):
    return ('"identity.kfx: generated by scripts/compiler-identity.py (C399), a\n'
            ' fingerprint of kc\'s sources: kc keeps a database as this kc\'s, and\n'
            ' takes none of another\'s. Not to be edited."\n'
            '(define kc-identity string "%s")\n' % ident)


UNITS = [
    ("kfx", "kfx.unit", ["prelude.fx"], kfx_text),
    # And the expander kc loads where it expands (C445, a file of a place,
    # in no unit): its expansions are its (C446). And its runtime: a
    # transformer's answer kept is its run (C448), its routines kcrt-core's
    # (C452).
    ("kc", "kc.unit", ["../fx26/macros/expander-kc.fx", "../fx26/macros/expander-types.fx",
                       "../crates/kayak-kcrt/src/lib.rs", "../crates/kayak-kcrt-core/src/lib.rs",
                       "../crates/kayak-kcrt-core/src/gc.rs"], kc_text),
]


def main():
    check = "--check" in sys.argv[1:]
    for d, unit, extra, text in UNITS:
        out = os.path.join(ROOT, d, "identity.kfx")
        ident = identity(sources(d, unit, extra))
        want = text(ident)
        have = open(out).read() if os.path.exists(out) else ""
        if check:
            if have != want:
                sys.exit("compiler-identity: %s/identity.kfx is not the sources' (scripts/regen.sh, or this script, writes it)" % d)
            print("compiler-identity: %s/identity.kfx is the sources'" % d)
            continue
        if have != want:
            with open(out, "w") as f:
                f.write(want)
        print("compiler-identity: %s %s" % (d, ident))


main()
